// Run the checks and write validation.json. The app only renders that file; it never decides a pass.
import { writeFileSync, mkdirSync } from 'node:fs';
import { demHeight, southPolarXY, type DemGrid } from '../engine/terrain.ts';
import { haveLocalRaster, localRaster, openRaster, pixelWindow, PRODUCTS, readWindow } from './dem.ts';
import { directionResiduals, loadTable, summarize } from './direction-check.ts';
import { engineVersion } from './engine-version.ts';
import { loadSites, siteFile } from './fetch-fixtures.ts';
import { CRATERS, orientationCheck, RING_POINTS, type HeightAt } from './raster-orientation.ts';
import { REFINEMENT_LIMIT_GAP_PCT, REFINEMENT_LIMIT_POINTS, refinementCheck, SKYLINE_THRESHOLD_DEG, syntheticCases, type CheckOptions } from './skyline-check.ts';
import { SKYLINE_DIR, verifySkylineFiles } from './skyline-files.ts';

export const VALIDATION_FILE = 'app/public/data/validation.json';
export const DIRECTION_THRESHOLD_DEG = 0.02;

export interface ValidationRow {
  id: string;
  name: string;
  n: number;
  /** Null for a check that is not measured in degrees. */
  maxDeg: number | null;
  rmsDeg: number | null;
  thresholdDeg: number | null;
  pass: boolean;
  fixtureFiles: string[];
  runAtUtc: string;
  engineCommit: string;
  detail: unknown;
  notes: string[];
}

export function runDirectionCheck(): ValidationRow {
  const sites = loadSites();
  const res = directionResiduals(loadTable(), sites);
  const all = summarize(res);
  const per = sites.flatMap((s) => (['sun', 'earth'] as const).map((body) => {
    const m = summarize(res.filter((x) => x.site === s.id && x.body === body));
    return { site: s.id, body, n: m.n, maxDeg: m.maxDeg, rmsDeg: m.rmsDeg };
  }));
  const sun = summarize(res.filter((x) => x.body === 'sun'));
  const earth = summarize(res.filter((x) => x.body === 'earth'));
  return {
    id: 'sun-earth-direction',
    name: 'Sun and Earth direction check against JPL Horizons',
    n: all.n,
    maxDeg: all.maxDeg,
    rmsDeg: all.rmsDeg,
    thresholdDeg: DIRECTION_THRESHOLD_DEG,
    pass: all.maxDeg <= DIRECTION_THRESHOLD_DEG,
    fixtureFiles: [
      ...sites.flatMap((s) => [siteFile(s.id, 'sun'), siteFile(s.id, 'earth')]),
      'fixtures/horizons/global/moon-<year>.txt, 2023 to 2040',
    ],
    runAtUtc: new Date().toISOString(),
    engineCommit: engineVersion(),
    detail: {
      sun: { n: sun.n, maxDeg: sun.maxDeg, rmsDeg: sun.rmsDeg },
      earth: { n: earth.n, maxDeg: earth.maxDeg, rmsDeg: earth.rmsDeg },
      perSite: per,
      worst: { site: all.worst.site, body: all.worst.body, utc: new Date(all.worst.tMs).toISOString(), deg: all.worst.deg },
      epochs: 'about 500 per site and body, every 18937 minutes from 2023-01-01 00:07 UTC, so most fall between hourly table rows',
    },
    notes: [
      'Angle is measured between unit vectors in the local frame, not as separate azimuth and elevation differences.',
      'Measured: the Earth direction carries almost all of the residual (up to about 0.006 degrees); the Sun direction differs by under 0.0003 degrees.',
      'Likely cause of the Earth residual, not yet verified: Horizons site queries use apparent (airless) positions, which include stellar aberration of up to about 0.006 degrees, and the hourly table does not.',
    ],
  };
}

/** Skyline maths on synthetic terrain with a known horizon, plus the refinement test. `opt` exists for the sabotage tests. */
export function runSkylineCheck(opt: CheckOptions = {}, refinementExtentM?: [number, number, number]): ValidationRow {
  const cases = syntheticCases(opt);
  const refinement = refinementCheck(loadTable(), opt.build, refinementExtentM);
  const n = cases.reduce((a, c) => a + c.n, 0);
  const maxDeg = Math.max(...cases.map((c) => c.maxDeg));
  const failed = [...cases.filter((c) => !c.pass).map((c) => c.id), ...(refinement.pass ? [] : ['refinement'])];
  return {
    id: 'skyline-synthetic',
    name: 'Skyline maths check on synthetic terrain',
    n, maxDeg,
    rmsDeg: Math.sqrt(cases.reduce((a, c) => a + c.sumSq, 0) / n),
    thresholdDeg: SKYLINE_THRESHOLD_DEG,
    pass: failed.length === 0,
    fixtureFiles: ['none: the terrain is generated by pipeline/synthetic-terrain.ts; the refinement test also reads app/public/data/ephem/<year>.bin'],
    runAtUtc: new Date().toISOString(),
    engineCommit: engineVersion(),
    detail: {
      failed,
      cases: cases.map((c) => ({ id: c.id, name: c.name, n: c.n, maxDeg: c.maxDeg, pass: c.pass, ...c.detail })),
      refinement: { limitPercentagePoints: REFINEMENT_LIMIT_POINTS, limitGapPercentOfStay: REFINEMENT_LIMIT_GAP_PCT, ...refinement },
    },
    notes: [
      'Synthetic terrain only. This row says the skyline arithmetic is right; it says nothing about any real site.',
      'Expected horizons: the smooth-sphere dip for flat ground, and the largest atan2((R+z)cos(t) - (R+h), (R+z)sin(t)), t = s/R, along each ridge profile.',
      'Refinement: the step along each ray and the spacing between rays are both halved. The limits were read as: sunlit, Earth-visible and overlap percentages move by less than 1 percentage point, and the longest dark gap and link gap move by less than 1% of the stay length.',
      'The rough refinement terrain was reshaped twice before its result was accepted, to make the Sun and Earth cross its horizon so the metrics are informative. The limits were not changed.',
    ],
  };
}

/** Orientation of the real rasters. Returns null when no raster is in data/ or data-raw/ (nothing is fetched by the validation run). */
export async function runOrientationCheck(): Promise<ValidationRow | null> {
  const products = PRODUCTS.filter(haveLocalRaster);
  if (products.length === 0) return null;
  const perRaster = [];
  for (const p of products) {
    const r = (await openRaster(p, false))!;
    const windows: DemGrid[] = [];
    const heightAt: HeightAt = async (latDeg, eLonDeg) => {
      const { x, y } = southPolarXY(latDeg, eLonDeg);
      for (const g of windows) { const z = demHeight(g, x, y); if (Number.isFinite(z)) return z; }
      const win = pixelWindow(r.header, x, y, 60_000);
      if (!win) return NaN;
      const g = await readWindow(r, win);
      windows.push(g);
      return demHeight(g, x, y);
    };
    perRaster.push({ raster: p.name, file: p.file, craters: await orientationCheck(heightAt) });
  }
  const all = perRaster.flatMap((x) => x.craters);
  return {
    id: 'raster-orientation',
    name: 'Elevation raster orientation check on two named craters',
    n: all.length, maxDeg: null, rmsDeg: null, thresholdDeg: null,
    pass: all.every((c) => c.pass),
    fixtureFiles: products.map((p) => localRaster(p)),
    runAtUtc: new Date().toISOString(),
    engineCommit: engineVersion(),
    detail: { rule: `centre below the median of ${RING_POINTS} points one crater radius away, and below the point at the mirrored longitude`, craters: CRATERS, perRaster },
    notes: ['Crater coordinates are the IAU Gazetteer values (Features 5450 and 953), verified against the gazetteer pages on 2026-11-15; they match the gazetteer\'s primary listing for each feature. Heights are metres above the 1,737.4 km sphere.'],
  };
}

/** Every shipped skyline must still match the record written when it was built. Null when no skyline is shipped. */
export function runSkylineFileCheck(dir = SKYLINE_DIR): ValidationRow | null {
  const v = verifySkylineFiles(dir);
  if (v.files === 0) return null;
  return {
    id: 'skyline-files',
    name: 'Shipped skylines match their build records',
    n: v.files, maxDeg: null, rmsDeg: null, thresholdDeg: null,
    pass: v.problems.length === 0,
    fixtureFiles: [`${dir}/<site>-<height>m.bin and .json`],
    runAtUtc: new Date().toISOString(),
    engineCommit: engineVersion(),
    detail: { problems: v.problems },
    notes: ['Each file is compared with the checksums in its record, in blocks of 10 degrees of azimuth.'],
  };
}

async function main() {
  const rows = [runDirectionCheck(), runSkylineCheck()];
  const pending: Array<{ id: string; name: string; reason: string }> = [];
  const orientation = await runOrientationCheck();
  if (orientation) rows.push(orientation);
  else pending.push({ id: 'raster-orientation', name: 'Elevation raster orientation check on two named craters', reason: `no LOLA raster in data/ or data-raw/; this check has not been run` });
  const files = runSkylineFileCheck();
  if (files) rows.push(files);
  else pending.push({ id: 'skyline-files', name: 'Shipped skylines match their build records', reason: `no skyline in ${SKYLINE_DIR}/; none has been built yet` });
  mkdirSync('app/public/data', { recursive: true });
  writeFileSync(VALIDATION_FILE, JSON.stringify({ generatedBy: 'pipeline/validate.ts', rows, pending }, null, 2) + '\n');
  for (const r of rows) {
    console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${r.name}`);
    if (r.maxDeg !== null) console.log(`  n = ${r.n}, max = ${r.maxDeg.toFixed(5)} deg, rms = ${r.rmsDeg!.toFixed(5)} deg, threshold = ${r.thresholdDeg} deg`);
    else console.log(`  n = ${r.n}`);
    const d = r.detail as { failed?: string[]; problems?: string[] };
    for (const line of [...(d.failed ?? []), ...(d.problems ?? [])]) console.log(`  failed: ${line}`);
  }
  for (const p of pending) console.log(`PENDING  ${p.name}\n  ${p.reason}`);
  console.log(`wrote ${VALIDATION_FILE}`);
  if (rows.some((r) => !r.pass)) process.exit(1);
}
if (import.meta.url === `file://${process.argv[1]}`) await main();
